use serde::{Deserialize, Serialize};

/// Zulip 用户设置中本客户端用到的字段。字段名与服务器一致。
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct UserSettings {
    pub color_scheme: i32,
    pub enter_sends: bool,
    pub twenty_four_hour_time: bool,
    pub enable_desktop_notifications: bool,
    pub enable_sounds: bool,
    pub notification_sound: String,
    pub pm_content_in_desktop_notifications: bool,
    pub enable_stream_desktop_notifications: bool,
    pub enable_stream_audible_notifications: bool,
    pub enable_followed_topic_desktop_notifications: bool,
    pub enable_followed_topic_audible_notifications: bool,
    pub wildcard_mentions_notify: bool,
    /// 草稿同步到服务器，否则只保存在本机。
    pub enable_drafts_synchronization: bool,
    pub send_read_receipts: bool,
    pub send_private_typing_notifications: bool,
    pub send_stream_typing_notifications: bool,
    pub presence_enabled: bool,
    pub email_address_visibility: i32,
    pub emojiset: String,
    pub display_emoji_reaction_users: bool,
    pub automatically_follow_topics_policy: i32,
    pub automatically_unmute_topics_in_muted_streams_policy: i32,
    pub starred_message_counts: bool,
    pub enable_offline_push_notifications: bool,
    pub enable_online_push_notifications: bool,
    pub enable_stream_push_notifications: bool,
    pub enable_followed_topic_push_notifications: bool,
    pub enable_offline_email_notifications: bool,
    pub enable_stream_email_notifications: bool,
    pub enable_followed_topic_email_notifications: bool,
    pub enable_followed_topic_wildcard_mentions_notify: bool,
    pub email_notifications_batching_period_seconds: i32,
    pub message_content_in_email_notifications: bool,
    pub realm_name_in_email_notifications_policy: i32,
    pub enable_digest_emails: bool,
    pub enable_login_emails: bool,
    pub enable_marketing_emails: bool,
    pub automatically_follow_topics_where_mentioned: bool,
}

impl Default for UserSettings {
    fn default() -> Self {
        Self {
            color_scheme: 1,
            enter_sends: false,
            twenty_four_hour_time: false,
            enable_desktop_notifications: true,
            enable_sounds: true,
            notification_sound: String::new(),
            pm_content_in_desktop_notifications: true,
            enable_stream_desktop_notifications: false,
            enable_stream_audible_notifications: false,
            enable_followed_topic_desktop_notifications: true,
            enable_followed_topic_audible_notifications: true,
            wildcard_mentions_notify: true,
            enable_drafts_synchronization: true,
            send_read_receipts: true,
            send_private_typing_notifications: true,
            send_stream_typing_notifications: true,
            presence_enabled: true,
            email_address_visibility: 1,
            emojiset: "google".to_owned(),
            display_emoji_reaction_users: true,
            automatically_follow_topics_policy: 3,
            automatically_unmute_topics_in_muted_streams_policy: 2,
            starred_message_counts: false,
            enable_offline_push_notifications: true,
            enable_online_push_notifications: true,
            enable_stream_push_notifications: false,
            enable_followed_topic_push_notifications: true,
            enable_offline_email_notifications: true,
            enable_stream_email_notifications: false,
            enable_followed_topic_email_notifications: true,
            enable_followed_topic_wildcard_mentions_notify: true,
            email_notifications_batching_period_seconds: 120,
            message_content_in_email_notifications: true,
            realm_name_in_email_notifications_policy: 1,
            enable_digest_emails: true,
            enable_login_emails: true,
            enable_marketing_emails: true,
            automatically_follow_topics_where_mentioned: true,
        }
    }
}
